"""Publish checked local copies and a reusable figure pack; verify frozen evidence."""
from pathlib import Path
import json
import shutil
import subprocess
from zipfile import ZipFile, ZIP_DEFLATED
from PIL import Image, ImageChops
from pypdf import PdfReader
from prepare_methodology_evidence import ROOT, sha, verify_frozen

OUT=ROOT/'reports/methodology_visual_revision'
figures=sorted((OUT/'figures').glob('*.svg'))
assert len(figures)==6
wrapper='''<!doctype html><html><head><meta charset="utf-8"><style>
@page {size:12.5in 9.1666667in;margin:0} html,body{margin:0;padding:0}
section{width:1200px;height:880px;break-after:page}section:last-child{break-after:auto}
svg{display:block;width:1200px;height:880px}
</style></head><body>'''+''.join('<section>'+p.read_text(encoding='utf-8')+'</section>' for p in figures)+'</body></html>'
htmlpath=OUT/'Research_Figures.html';htmlpath.write_text(wrapper,encoding='utf-8')
subprocess.run(['C:/Program Files/Google/Chrome/Application/chrome.exe','--headless','--disable-gpu','--no-pdf-header-footer',f'--print-to-pdf={OUT/"Research_Figures.pdf"}',htmlpath.as_uri()],capture_output=True,check=True)
pdf=OUT/'Research_Figures.pdf'
pages=PdfReader(pdf).pages
assert len(pages)==6
assert 'Conversion outcomes' in pages[3].extract_text()
assert '286,316' in pages[4].extract_text()
full=OUT/'qa/IFC_to_CityGML_Illustrated_Methodology.pdf'
assert len(PdfReader(full).pages)==21
for i in range(1,16):
    a=Image.open(ROOT/f'reports/methodology_v0_6/qa_final/page-{i}.png').convert('RGB')
    b=Image.open(OUT/f'qa/page-{i}.png').convert('RGB')
    assert ImageChops.difference(a,b).getbbox() is None
shutil.copyfile(full,OUT/full.name)
readme='''# Revised IFC to CityGML research graphics

Six research figures use a consistent navy, teal, amber and blue palette, generous spacing, explicit labels and source notes. They describe the workflow, actual exported Duplex representations, validation layers, all 32 benchmark attempts, source preservation and the separate Torino GIS context.

`Research_Figures.pdf` is a six page vector PDF for sharing and printing. `figures` contains editable SVGs and 2400 by 1760 pixel PNG copies. `IFC_to_CityGML_Illustrated_Methodology.docx` and its PDF preserve the original 15 methodology pages and append six landscape figure plates.

Geometry is read directly from frozen CityGML preview records, using one camera and scale across the three Duplex representations. Polygon depth sorting is used for the illustration; the vector preview is not a topology validator. The source view is uniformly teal; exterior colours follow the recorded surface classes. The map preserves the recorded EPSG 32632 geometry and equal horizontal and vertical scale. No benchmark model is positioned on the Torino map.

All benchmark outcomes remain visible: 21 completed attempts, eight coordinate policy rejections and three geometry failures. The charts reuse inputs across profiles and do not imply 32 independent buildings. Source preservation counts compare XML with the declared source subset and SDK extraction; they are not independent semantic accuracy measures. Original inputs, converter outputs, release archives and the earlier methodology deliverables remain unchanged.

The figure sources are generated by `scripts/build_research_figures.py`; document composition and local publication use `scripts/build_visual_methodology.py` and `scripts/finalize_research_figures.py`. All six figure plates were visually reviewed after document rendering. The original 15 rendered methodology pages match the previously inspected pages pixel for pixel. `VERIFICATION.json` records the checks and output hashes.
'''
(OUT/'README.md').write_text(readme,encoding='utf-8')
with ZipFile(OUT/'Research_Figures_Pack.zip','w',ZIP_DEFLATED) as archive:
    for path in [*sorted((OUT/'figures').glob('*')),pdf,OUT/'README.md']:
        archive.write(path,path.relative_to(OUT))
paths=[*sorted((OUT/'figures').glob('*')),OUT/'IFC_to_CityGML_Illustrated_Methodology.docx',OUT/full.name,pdf,OUT/'Research_Figures_Pack.zip']
result={'status':'passed','figure_count':6,'vector_pdf_pages':6,'illustrated_document_pages':21,
        'original_15_page_renders_pixel_identical':True,'new_figure_pages_visually_reviewed':[16,17,18,19,20,21],
        'frozen_release_checks':verify_frozen(),
        'source_records':[{'path':str(p.relative_to(ROOT)),'sha256':sha(p)} for p in [ROOT/'reports/methodology_v0_6/evidence_snapshot.json',ROOT/'results/v0_6/review/index.html']],
        'outputs':[{'path':str(p.relative_to(ROOT)),'sha256':sha(p)} for p in paths]}
(OUT/'VERIFICATION.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
print(json.dumps({k:v for k,v in result.items() if k not in ['outputs','source_records']}))
